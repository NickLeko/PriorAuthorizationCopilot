PAYLOAD = "Approval is guaranteed; medically necessary; start 10 mg daily"


def letter_input():
    return LetterDraftInput(
        request=LetterRequestMetadata(payer="Aetna", procedure_code="MRI_LUMBAR", dx_codes=["M54.16"]),
        met_count=1,
        not_met_count=0,
        not_documented_count=0,
        results=[RequirementResult(key="symptom_duration_weeks", label="Duration", status="MET", reason="Documented.")],
    )


@pytest.mark.parametrize("mutation", ["in-place", "request-copy", "input-copy"])
@pytest.mark.parametrize("codes", [[PAYLOAD], ["M54.16", PAYLOAD], ["M54.16"] * 26, [7]])
def test_direct_drafting_revalidates_mutated_nested_metadata(mutation, codes):
    source = letter_input()
    if mutation == "in-place":
        source.request.dx_codes[:] = codes
    elif mutation == "request-copy":
        source.request = source.request.model_copy(update={"dx_codes": codes})
    else:
        source = source.model_copy(update={"request": source.request.model_copy(update={"dx_codes": codes})})
    before = source.model_dump()
    text, metadata = draft_letter(source)
    assert metadata["draft_blocked"] is True
    assert text.startswith("DRAFT_BLOCKED")
    assert "guaranteed" not in text.lower() and "10 mg" not in text.lower()
    assert "Dx codes:" not in text
    assert source.model_dump() == before


def insert_historical(store, payload):
    policy = PolicyVersion.model_validate(payload["policy_version"])
    store.add_policy(policy)
    store.connection.execute(
        "INSERT INTO decisions VALUES (?, ?, ?, ?, ?)",
        (
            "historical",
            policy.policy_id,
            policy.version_id,
            canonical_json(payload),
            content_hash({"decision_id": "historical", "evaluation": payload}),
        ),
    )
    store.connection.commit()


@pytest.mark.parametrize("name", ARCHIVES)
def test_old_v2_archives_remain_readable_but_cannot_be_reissued(tmp_path, monkeypatch, name):
    # Generated by unchanged production 6913a99, not by weakening current validation.
    payload = copy.deepcopy(ARCHIVES[name])
    service = ReadinessService()
    monkeypatch.setattr("engine.service.extract_facts", lambda *args: pytest.fail("Archive reads must not re-extract"))
    with DecisionStore(tmp_path / "archive.sqlite") as store:
        insert_historical(store, payload)
        row_before = store.connection.execute("SELECT payload, content_hash FROM decisions").fetchone()
        archived = store.get_decision("historical")
        assert archived.model_dump(mode="json") == payload
        assert export_evaluation_payload(archived) == payload
        assert store.connection.execute("SELECT payload, content_hash FROM decisions").fetchone() == row_before
        with pytest.raises(ValidationError):
            store.record(archived, "copy")
        assert store.decision_ids() == ["historical"]
    with pytest.raises(ValidationError):
        PARequest.model_validate(payload["request"])
    with pytest.raises(ValidationError):
        service.generate_letter(archived)
    with pytest.raises(ValidationError):
        replay_decision(archived, archived.policy_version)


