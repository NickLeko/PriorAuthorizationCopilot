def test_non_utf8_drift_log_is_a_controlled_fail_closed_status(tmp_path):
    root = tmp_path / "repo"
    for name in ("rules", "rulebook", "policy_snapshots", "inputs"):
        shutil.copytree(ROOT / name, root / name)
    (root / "policy_snapshots/drift_log.jsonl").write_bytes(b"\xff")
    service = ReadinessService(load_app_config(root))
    report = service.get_drift_status()
    assert report.any_review_required
    assert report.sources[0].status == "INVALID_DRIFT_LOG"
    assert "UTF-8" in report.sources[0].review_reason
    assert str(root) not in report.sources[0].review_reason
    result = service.evaluate(service.get_demo_case_request("MRI-01-complete"))
    assert result.policy_trust_level == "demo"
    assert result.submission_readiness is False
